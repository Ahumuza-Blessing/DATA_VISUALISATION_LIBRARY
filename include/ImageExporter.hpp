#ifndef IMAGEEXPORTER_HPP // Prevents the header from being included more than once
#define IMAGEEXPORTER_HPP // Defines the header guard

#include <string> // Provides std::string for storing filenames, paths and SVG text

// The Renderer gives us the SVG text, but we still need to save it.
// By default I want the finished images in the project's data/output folder.
class ImageExporter {
public: // Makes these functions accessible to other modules

    // This tells us the full location where a graph will be saved.
    // static means we can call this function without creating an ImageExporter object.
    // const std::string& avoids copying the filename and prevents modification.
    // The function returns the resolved file path as a string.
    static std::string outputFile(const std::string& filename);

    // Save the SVG and create its destination folder if necessary.
    // svg contains the SVG markup generated by the Renderer.
    // filePath specifies the name or location where the SVG should be saved.
    // void means the function does not return a value.
    static void saveSVG(const std::string& svg, const std::string& filePath);
};

#endif // Ends the header guard
